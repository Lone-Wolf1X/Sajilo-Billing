import 'dart:convert';
import 'package:drift/native.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:sajilo_billing/core/database/app_database.dart';
import 'package:sajilo_billing/core/utils/paisa_helper.dart';
import 'package:sajilo_billing/features/inventory/data/inventory_import_export_service.dart';

void main() {
  late AppDatabase db;
  late InventoryImportExportService service;

  setUp(() {
    db = AppDatabase(NativeDatabase.memory());
    service = InventoryImportExportService(db);
  });

  tearDown(() async {
    await db.close();
  });

  group('InventoryImportExportService - Templates', () {
    test('generateCsvTemplate produces non-empty CSV string with headers', () {
      final csv = service.generateCsvTemplate();
      expect(csv, contains('Item Name*'));
      expect(csv, contains('Selling Price (Rs)*'));
      expect(csv, contains('Casio Watch Standard'));
    });

    test('generateExcelTemplate produces valid non-empty byte buffer', () {
      final bytes = service.generateExcelTemplate();
      expect(bytes.isNotEmpty, isTrue);
      expect(bytes.length, greaterThan(100));
    });
  });

  group('InventoryImportExportService - Parsing', () {
    test('parseCsv handles standard CSV with headers and Nepali text', () {
      const csvData = '''Item Name*,Nepali Name,SKU / Barcode*,Category,Unit,Cost Price (Rs)*,Selling Price (Rs)*,Opening Stock,Low Stock Alert
Wai Wai Noodles,वाइ वाइ चाउचाउ,WAI-01,Groceries,packet,20,25,50,10
Parle-G Biscuits,पारले-जी,PAR-01,Bakery,packet,10,12,100,20
''';
      final bytes = utf8.encode(csvData);
      final rows = service.parseCsv(bytes);

      expect(rows.length, 2);
      expect(rows[0].name, 'Wai Wai Noodles');
      expect(rows[0].nepaliName, 'वाइ वाइ चाउचाउ');
      expect(rows[0].sku, 'WAI-01');
      expect(rows[0].category, 'Groceries');
      expect(rows[0].unit, 'packet');
      expect(rows[0].purchasePrice, 20.0);
      expect(rows[0].sellingPrice, 25.0);
      expect(rows[0].stockQty, 50.0);
      expect(rows[0].lowStockThreshold, 10.0);

      expect(rows[1].name, 'Parle-G Biscuits');
      expect(rows[1].sku, 'PAR-01');
    });

    test('parseCsv strips UTF-8 BOM properly', () {
      const csvData = '\uFEFFItem Name*,SKU,Cost Price,Selling Price\nApple iPhone,IPHONE-15,100000,120000\n';
      final bytes = utf8.encode(csvData);
      final rows = service.parseCsv(bytes);

      expect(rows.length, 1);
      expect(rows[0].name, 'Apple iPhone');
      expect(rows[0].sku, 'IPHONE-15');
      expect(rows[0].purchasePrice, 100000.0);
      expect(rows[0].sellingPrice, 120000.0);
    });

    test('parseCsv auto-generates SKU if omitted', () {
      const csvData = '''Item Name*,Selling Price
Loose Sugar,120
''';
      final bytes = utf8.encode(csvData);
      final rows = service.parseCsv(bytes);

      expect(rows.length, 1);
      expect(rows[0].name, 'Loose Sugar');
      expect(rows[0].sku, startsWith('AUTO-'));
      expect(rows[0].sellingPrice, 120.0);
    });

    test('parseExcel parses bytes generated by generateExcelTemplate', () {
      final excelBytes = service.generateExcelTemplate();
      final rows = service.parseExcel(excelBytes);

      expect(rows.length, 4);
      expect(rows[0].name, 'Casio Watch Standard');
      expect(rows[0].sku, 'SKU-5001');
      expect(rows[0].purchasePrice, 1500.0);
      expect(rows[0].sellingPrice, 2200.0);
      expect(rows[0].stockQty, 10.0);
    });
  });

  group('InventoryImportExportService - Database Import', () {
    test('importRows inserts new products and creates categories', () async {
      final rows = [
        ProductImportRow(
          name: 'Colgate Toothpaste 150g',
          nepaliName: 'कोलगेट',
          sku: 'COLG-150',
          category: 'Personal Care',
          unit: 'tube',
          purchasePrice: 120.0,
          sellingPrice: 150.0,
          stockQty: 25.0,
          lowStockThreshold: 5.0,
        ),
      ];

      final result = await service.importRows(rows);
      expect(result.insertedCount, 1);
      expect(result.updatedCount, 0);
      expect(result.failedCount, 0);
      expect(result.hasErrors, isFalse);

      // Verify item in database
      final items = await db.select(db.items).get();
      final item = items.firstWhere((i) => i.sku == 'COLG-150');
      expect(item.name, 'Colgate Toothpaste 150g');
      expect(item.nepaliName, 'कोलगेट');
      expect(item.purchasePricePaisa, PaisaHelper.toPaisa(120.0));
      expect(item.sellingPricePaisa, PaisaHelper.toPaisa(150.0));
      expect(item.stockQty, 25.0);

      // Verify category was created
      final categories = await db.select(db.categories).get();
      expect(categories.any((c) => c.name == 'Personal Care'), isTrue);

      // Verify opening stock ledger entry
      final ledger = await db.select(db.stockLedger).get();
      final entry = ledger.firstWhere((l) => l.itemId == item.id);
      expect(entry.qtyChange, 25.0);
      expect(entry.reason, 'INITIAL_STOCK');
      expect(entry.refType, 'CSV_IMPORT');
    });

    test('importRows updates existing product if SKU matches', () async {
      final row1 = ProductImportRow(
        name: 'Dabur Honey 250g',
        sku: 'DABUR-250',
        purchasePrice: 180.0,
        sellingPrice: 220.0,
        stockQty: 10.0,
      );
      await service.importRows([row1]);

      // Now import update with new price and name
      final rowUpdate = ProductImportRow(
        name: 'Dabur Pure Honey 250g (Special)',
        sku: 'DABUR-250',
        purchasePrice: 190.0,
        sellingPrice: 240.0,
        stockQty: 10.0,
      );
      final result = await service.importRows([rowUpdate]);

      expect(result.insertedCount, 0);
      expect(result.updatedCount, 1);
      expect(result.failedCount, 0);

      final items = await db.select(db.items).get();
      final item = items.firstWhere((i) => i.sku == 'DABUR-250');
      expect(item.name, 'Dabur Pure Honey 250g (Special)');
      expect(item.sellingPricePaisa, PaisaHelper.toPaisa(240.0));
    });
  });
}
